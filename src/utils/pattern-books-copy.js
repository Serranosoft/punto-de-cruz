export function getPatternBooksCopy(locale = 'es') {
    return locale.toLowerCase().startsWith('es') ? copy.es : copy.en;
}

export function formatBookCopy(text, values) {
    return text.replace(/%\{(\w+)\}/g, (_, key) => String(values[key]));
}
