const { withAppBuildGradle } = require('@expo/config-plugins');

function toAndroidResourceConfiguration(locale) {
  return locale.includes('-') ? `b+${locale.replaceAll('-', '+')}` : locale;
}

module.exports = function withAndroidResourceLocales(config) {
  return withAppBuildGradle(config, (gradleConfig) => {
    if (gradleConfig.modResults.language !== 'groovy') {
      return gradleConfig;
    }

    let foundResourceConfigurations = false;
    gradleConfig.modResults.contents = gradleConfig.modResults.contents.replace(
      /resourceConfigurations\s*\+=\s*\[[^\]]*\]/,
      (resourceConfigurations) => {
        foundResourceConfigurations = true;
        return resourceConfigurations.replace(
          /"([^"]+)"/g,
          (_match, locale) => `"${toAndroidResourceConfiguration(locale)}"`
        );
      }
    );

    if (!foundResourceConfigurations) {
      throw new Error(
        'Unable to find the resourceConfigurations generated by expo-localization.'
      );
    }

    return gradleConfig;
  });
};

module.exports.toAndroidResourceConfiguration = toAndroidResourceConfiguration;
